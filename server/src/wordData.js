function getWordsByCategory(category) {
  return WORD_DATA[category] || [];
}

function getAllCategories() {
  return Object.keys(WORD_DATA);
}

function getRandomWord(category) {
  const words = getWordsByCategory(category);
  if (words.length === 0) return null;
  return words[Math.floor(Math.random() * words.length)];
}

function getRandomCategory() {
  const categories = getAllCategories();
  return categories[Math.floor(Math.random() * categories.length)];
}

function getFoolModeWordPair(citizenWord) {
  const pairs = FOOL_MODE_PAIRS[citizenWord];
  if (pairs && pairs.length > 0) {
    return pairs[Math.floor(Math.random() * pairs.length)];
  }
  // 같은 카테고리에서 다른 단어 선택
  for (const [category, words] of Object.entries(WORD_DATA)) {
    if (words.includes(citizenWord)) {
      const otherWords = words.filter(w => w !== citizenWord);
      if (otherWords.length > 0) {
        return otherWords[Math.floor(Math.random() * otherWords.length)];
      }
    }
  }
  return null;
}

